CREATE TABLE MAP_PLACE (
    IDX INT NOT NULL AUTO_INCREMENT COMMENT '장소 순번',
    PLACE_IDX INT NOT NULL COMMENT '관광지/맛집 IDX',
    PLACE_CODE VARCHAR(50) NOT NULL COMMENT '장소 코드',
    MARKER_ICON_TYPE VARCHAR(30) NOT NULL COMMENT '마커 아이콘',
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '생성일시',
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '수정일시',
    PRIMARY KEY (IDX)
) COMMENT='지도 장소';
