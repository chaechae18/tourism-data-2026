-- 팀에서 확정한 MySQL 스키마 (수신본 원문)
--
-- core/models.py 는 이 파일을 그대로 미러링합니다. 모델은 전부 managed=False 이며
-- Django 는 이 테이블들을 읽기만 합니다. 스키마 변경은 이 파일을 통해서만 일어납니다.
-- 보완 제안은 proposed-alter.sql 을 보세요.
--
-- 이 백엔드가 실제로 읽는 테이블은 7개입니다:
--   MAIN_BANNER, POPUP, POPUP_I18N, FESTIVAL, FESTIVAL_I18N, PLACE, CATEGORY
-- 나머지는 다른 팀원 담당이며 참고용으로 함께 보관합니다.

CREATE TABLE USERS (
    NO INT NOT NULL AUTO_INCREMENT COMMENT '사용자 NO',
    ID VARCHAR(100) NOT NULL COMMENT '사용자 고유 ID',
    NICKNAME VARCHAR(100) NOT NULL COMMENT '사용자 닉네임',
    COUNTRY VARCHAR(100) NOT NULL COMMENT '국가',
    BIRTH_DATE DATE DEFAULT NULL COMMENT '생년월일',
    EMAIL VARCHAR(255) NOT NULL COMMENT '이메일',
    PROFILE_IMAGE VARCHAR(500) DEFAULT NULL COMMENT '프로필 이미지 URL',
    STATUS TINYINT NOT NULL DEFAULT 1 COMMENT '회원 상태 (1: 사용중, 2: 휴면, 3: 탈퇴)',
    LANGUAGE_CODE VARCHAR(10) NOT NULL DEFAULT 'ko' COMMENT '언어 코드',
    LAST_VISITED_AT TIMESTAMP NULL DEFAULT NULL COMMENT '최근 방문일시',
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '생성일시',
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '수정일시',
    DELETED_AT TIMESTAMP NULL DEFAULT NULL COMMENT '탈퇴일시',
    PRIMARY KEY (NO),
    UNIQUE KEY UK_USERS_ID (ID)
) COMMENT='사용자 정보 테이블';

CREATE TABLE USER_AUTH (
    IDX INT NOT NULL AUTO_INCREMENT COMMENT '인증 정보 순번',
    USER_NO INT NOT NULL COMMENT '사용자 고유 NO',
    PASSWORD_HASH VARCHAR(255) DEFAULT NULL COMMENT '비밀번호 해시',
    PROVIDER TINYINT NOT NULL DEFAULT 1 COMMENT '로그인 방식 (1: 일반, 2: Google, 3: Kakao, 4: Naver)',
    PROVIDER_ID VARCHAR(255) DEFAULT NULL COMMENT '소셜 로그인 제공자 사용자 ID',
    EMAIL_VERIFIED TINYINT NOT NULL DEFAULT 0 COMMENT '이메일 인증 여부 (0: 미인증, 1: 인증)',
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '생성일시',
    PRIMARY KEY (IDX),
    CONSTRAINT FK_USER_AUTH_USERS FOREIGN KEY (USER_NO) REFERENCES USERS(NO) ON DELETE CASCADE
) COMMENT='사용자 인증 정보 테이블';

CREATE TABLE USER_CHARACTER (
